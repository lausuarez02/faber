/** HD44780 ROM A00 glyphs that differ from ASCII (5 columns, bit 0 = top). Original drawings. */
const ROM_A00: Record<number, readonly number[]> = {
  0x5c: [0x15, 0x16, 0x7c, 0x16, 0x15], // ¥
  0x7e: [0x08, 0x08, 0x2a, 0x1c, 0x08], // →
  0x7f: [0x08, 0x1c, 0x2a, 0x08, 0x08], // ←
  0xdf: [0x00, 0x07, 0x05, 0x07, 0x00], // °
};

/**
 * Rows of a character cell (8 rows, 5 bits each, bit 4 = leftmost), the CGRAM layout.
 * Unknown codes draw as an empty cell.
 */
export function glyphRows(code: number): number[] {
  const cols = ROM_A00[code] ?? (code >= 0x20 && code < 0x80 ? ASCII.slice((code - 0x20) * 5, (code - 0x20) * 5 + 5) : [0, 0, 0, 0, 0]);
  const rows: number[] = [];
  for (let r = 0; r < 8; r++) {
    let v = 0;
    for (let c = 0; c < 5; c++) if ((cols[c]! >> r) & 1) v |= 0x10 >> c;
    rows.push(v);
  }
  return rows;
}
