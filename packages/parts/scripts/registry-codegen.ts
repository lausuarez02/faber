// Pure codegen for src/registry.gen.ts. Used by scripts/gen-registry.ts (writes the file) and by
// src/spec.test.ts (checks the committed file is up to date).
import { existsSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { checkPartFolder } from "../src/spec/validate.ts";

export const PACKAGE_ROOT = fileURLToPath(new URL("..", import.meta.url));
export const PARTS_DIR = join(PACKAGE_ROOT, "src", "parts");
export const REGISTRY_FILE = join(PACKAGE_ROOT, "src", "registry.gen.ts");

export function listPartFolders(partsDir = PARTS_DIR): string[] {
  if (!existsSync(partsDir)) return [];
  return readdirSync(partsDir)
    .filter((d) => statSync(join(partsDir, d)).isDirectory())
    .sort();
}

export interface Rendered {
  code: string;
  problems: string[];
  count: number;
}

export function renderRegistry(partsDir = PARTS_DIR): Rendered {
  const problems: string[] = [];
  const entries: string[] = [];
  const imports: string[] = [];
  const folders = listPartFolders(partsDir);
  folders.forEach((dir, i) => {
    const f = checkPartFolder(partsDir, dir);
    problems.push(...f.problems);
    if (!f.spec || !f.fidelity || f.svg === undefined) return;
    const ident = `create_${i}`;
    imports.push(`import { create as ${ident} } from "./parts/${dir}/model.ts";`);
    const json = (v: unknown) => JSON.stringify(v, null, 2).replace(/\n/g, "\n    ");
    entries.push(
      `  {\n    spec: ${json(f.spec)},\n    fidelity: ${json(f.fidelity)},\n    svg: ${JSON.stringify(f.svg)},\n    create: ${ident},\n  },`,
    );
  });
  const code = `// GENERATED by packages/parts/scripts/gen-registry.ts. Do not edit; run \`pnpm gen\`.
import { createRegistry, type PartDefinition, type PartRegistry } from "@jumper/sim-core";
${imports.join("\n")}

export const partDefinitions: PartDefinition[] = [
${entries.join("\n")}
];

export const registry: PartRegistry = createRegistry(partDefinitions);
`;
  return { code, problems, count: folders.length };
}
