// Writes esp_audio/tone_wav.h: a 0.25 s, 440 Hz sine WAV (16 kHz, mono, 16-bit PCM, half scale) as a
// const byte array, so the fixture plays "a WAV from flash". Deterministic; rerun only on purpose.
//   node packages/sim-backends/fixtures/esp32/gen-tone-wav.mjs
import { writeFileSync } from "node:fs";

const rate = 16000, hz = 440, frames = 4000;
const data = Buffer.alloc(frames * 2);
for (let i = 0; i < frames; i++) data.writeInt16LE(Math.round(16384 * Math.sin((2 * Math.PI * hz * i) / rate)), 2 * i);
const h = Buffer.alloc(44);
h.write("RIFF", 0); h.writeUInt32LE(36 + data.length, 4); h.write("WAVE", 8);
h.write("fmt ", 12); h.writeUInt32LE(16, 16); h.writeUInt16LE(1, 20); h.writeUInt16LE(1, 22);
h.writeUInt32LE(rate, 24); h.writeUInt32LE(rate * 2, 28); h.writeUInt16LE(2, 32); h.writeUInt16LE(16, 34);
h.write("data", 36); h.writeUInt32LE(data.length, 40);
const all = Buffer.concat([h, data]);
const rows = [];
for (let i = 0; i < all.length; i += 24) rows.push("  " + [...all.subarray(i, i + 24)].map((b) => `0x${b.toString(16).padStart(2, "0")}`).join(", ") + ",");
writeFileSync(new URL("esp_audio/tone_wav.h", import.meta.url), `// 440 Hz sine, 16 kHz mono 16-bit PCM WAV, 0.25 s. Generated by ../gen-tone-wav.mjs.\n#pragma once\n#include <stdint.h>\nconst uint8_t tone_wav[${all.length}] = {\n${rows.join("\n")}\n};\n`);
